`timescale 1ns/1ps

module test_bf16_array;

    parameter int N = 4;

    logic clk;
    logic rst_n;
    logic enable;

    logic [15:0] a_input [0:N-1];
    logic [15:0] b_input [0:N-1];

    logic a_valid [0:N-1];
    logic b_valid [0:N-1];

    logic [31:0] c_output [0:N-1][0:N-1];
    logic c_valid [0:N-1][0:N-1];


    bf16_mac_array #(
        .N(N)
    ) dut (
        .clk(clk),
        .rst_n(rst_n),
        .enable(enable),

        .a_input(a_input),
        .b_input(b_input),

        .a_valid(a_valid),
        .b_valid(b_valid),

        .c_output(c_output),
        .c_valid(c_valid)
    );


    always #5 clk = ~clk;

    /*
     * ============================================================
     * DEBUG: PE[0][0]
     * ============================================================
     */
    always @(posedge clk) begin
        if ($time < 300) begin
            $display(
                "[DEBUG t=%0t] rst_n=%b enable=%b Avalid=%b Bvalid=%b | PE00 acc_valid=%b acc=%h",
                $time,
                rst_n,
                enable,
                dut.a_valid_wire[0][0],
                dut.b_valid_wire[0][0],
                dut.GEN_ROWS[0].GEN_COLS[0].pe.acc_valid,
                dut.GEN_ROWS[0].GEN_COLS[0].pe.acc_out
            );
        end
    end



    /*
     * Integer -> BF16 constants for values 1..7.
     */
    function automatic [15:0] int_to_bf16(
        input integer value
    );
        begin
            case (value)

                1: int_to_bf16 = 16'h3F80;
                2: int_to_bf16 = 16'h4000;
                3: int_to_bf16 = 16'h4040;
                4: int_to_bf16 = 16'h4080;
                5: int_to_bf16 = 16'h40A0;
                6: int_to_bf16 = 16'h40C0;
                7: int_to_bf16 = 16'h40E0;

                default:
                    int_to_bf16 = 16'h0000;

            endcase
        end
    endfunction


    /*
     * Expected FP32 representations for integer values
     * generated by the matrix multiplication.
     *
     * Maximum result here is small, so exact FP32
     * integer representation is sufficient.
     */
    function automatic [31:0] int_to_fp32(
        input integer value
    );
        begin
            case (value)

                 0: int_to_fp32 = 32'h00000000;
                 1: int_to_fp32 = 32'h3F800000;
                 2: int_to_fp32 = 32'h40000000;
                 3: int_to_fp32 = 32'h40400000;
                 4: int_to_fp32 = 32'h40800000;
                 5: int_to_fp32 = 32'h40A00000;
                 6: int_to_fp32 = 32'h40C00000;
                 7: int_to_fp32 = 32'h40E00000;
                 8: int_to_fp32 = 32'h41000000;
                 9: int_to_fp32 = 32'h41100000;
                10: int_to_fp32 = 32'h41200000;
                11: int_to_fp32 = 32'h41300000;
                12: int_to_fp32 = 32'h41400000;
                13: int_to_fp32 = 32'h41500000;
                14: int_to_fp32 = 32'h41600000;
                15: int_to_fp32 = 32'h41700000;
                16: int_to_fp32 = 32'h41800000;
                17: int_to_fp32 = 32'h41880000;
                18: int_to_fp32 = 32'h41900000;
                19: int_to_fp32 = 32'h41980000;
                20: int_to_fp32 = 32'h41A00000;
                21: int_to_fp32 = 32'h41A80000;
                22: int_to_fp32 = 32'h41B00000;
                23: int_to_fp32 = 32'h41B80000;
                24: int_to_fp32 = 32'h41C00000;
                25: int_to_fp32 = 32'h41C80000;
                26: int_to_fp32 = 32'h41D00000;
                27: int_to_fp32 = 32'h41D80000;
                28: int_to_fp32 = 32'h41E00000;
                29: int_to_fp32 = 32'h41E80000;
                30: int_to_fp32 = 32'h41F00000;
                31: int_to_fp32 = 32'h41F80000;
                32: int_to_fp32 = 32'h42000000;
                33: int_to_fp32 = 32'h42040000;
                34: int_to_fp32 = 32'h42080000;
                35: int_to_fp32 = 32'h420C0000;
                36: int_to_fp32 = 32'h42100000;
                37: int_to_fp32 = 32'h42140000;
                38: int_to_fp32 = 32'h42180000;
                39: int_to_fp32 = 32'h421C0000;
                40: int_to_fp32 = 32'h42200000;
                41: int_to_fp32 = 32'h42240000;
                42: int_to_fp32 = 32'h42280000;
                43: int_to_fp32 = 32'h422C0000;
                44: int_to_fp32 = 32'h42300000;
                45: int_to_fp32 = 32'h42340000;
                46: int_to_fp32 = 32'h42380000;
                47: int_to_fp32 = 32'h423C0000;
                48: int_to_fp32 = 32'h42400000;
                49: int_to_fp32 = 32'h42440000;
                50: int_to_fp32 = 32'h42480000;
                51: int_to_fp32 = 32'h424C0000;
                52: int_to_fp32 = 32'h42500000;
                53: int_to_fp32 = 32'h42540000;
                54: int_to_fp32 = 32'h42580000;
                55: int_to_fp32 = 32'h425C0000;
                56: int_to_fp32 = 32'h42600000;
                57: int_to_fp32 = 32'h42640000;
                58: int_to_fp32 = 32'h42680000;
                59: int_to_fp32 = 32'h426C0000;
                60: int_to_fp32 = 32'h42700000;
                61: int_to_fp32 = 32'h42740000;
                62: int_to_fp32 = 32'h42780000;
                63: int_to_fp32 = 32'h427C0000;
                64: int_to_fp32 = 32'h42800000;

                default:
                    int_to_fp32 = 32'hXXXXXXXX;

            endcase
        end
    endfunction


    integer A [0:N-1][0:N-1];
    integer B [0:N-1][0:N-1];

    integer expected [0:N-1][0:N-1];

    integer r;
    integer c;
    integer k;
    integer cycle;
    integer kk;

    initial begin

        clk = 1'b0;

        rst_n = 1'b0;
        enable = 1'b0;

        for (r = 0; r < N; r = r + 1) begin

            a_input[r] = 16'h0000;
            b_input[r] = 16'h0000;

            a_valid[r] = 1'b0;
            b_valid[r] = 1'b0;

        end


        /*
         * Matrix A.
         */
        for (r = 0; r < N; r = r + 1) begin
            for (c = 0; c < N; c = c + 1) begin
                A[r][c] = r + c + 1;
            end
        end


        /*
         * Matrix B.
         */
        for (r = 0; r < N; r = r + 1) begin
            for (c = 0; c < N; c = c + 1) begin
                B[r][c] = 7 - r - c;
            end
        end


        /*
         * Software reference.
         */
        for (r = 0; r < N; r = r + 1) begin

            for (c = 0; c < N; c = c + 1) begin

                expected[r][c] = 0;

                for (k = 0; k < N; k = k + 1) begin
                    expected[r][c] =
                        expected[r][c] +
                        A[r][k] * B[k][c];
                end

            end

        end


        $display("==============================================");
        $display("NAA BF16 4x4 SYSTOLIC TEST");
        $display("==============================================");


        /*
         * Reset.
         */
        repeat (4) begin
            @(posedge clk);
            #1;
        end

        @(negedge clk);
        rst_n = 1'b1;
        enable = 1'b1;


        /*
         * Wavefront feed.
         *
         * A[r][k] enters row r at:
         *     cycle = k + r
         *
         * B[k][c] enters column c at:
         *     cycle = k + c
         *
         * PE[r][c] receives product at:
         *     k + r + c
         */

        for (cycle = 0; cycle < (3*N + 4); cycle = cycle + 1) begin

            @(negedge clk);

            for (r = 0; r < N; r = r + 1) begin

                kk = cycle - r;

                if ((kk >= 0) && (kk < N)) begin

                    a_input[r] = int_to_bf16(A[r][kk]);
                    a_valid[r] = 1'b1;

                end
                else begin

                    a_input[r] = 16'h0000;
                    a_valid[r] = 1'b0;
                end

            end


            for (c = 0; c < N; c = c + 1) begin

                kk = cycle - c;

                if ((kk >= 0) && (kk < N)) begin

                    b_input[c] = int_to_bf16(B[kk][c]);
                    b_valid[c] = 1'b1;

                end
                else begin

                    b_input[c] = 16'h0000;
                    b_valid[c] = 1'b0;
                end

            end


            @(posedge clk);
            #1;

        end


        /*
         * Allow final wavefront to settle.
         */
        repeat (4)
            @(posedge clk);

        #1;


        /*
         * Verify all 16 outputs.
         */
        for (r = 0; r < N; r = r + 1) begin

            for (c = 0; c < N; c = c + 1) begin

                if (c_valid[r][c] !== 1'b1) begin

                    $display(
                        "[FAIL] C[%0d][%0d] valid=%b",
                        r,
                        c,
                        c_valid[r][c]
                    );

                    $fatal;

                end


                if (c_output[r][c] !== int_to_fp32(expected[r][c])) begin

                    $display(
                        "[FAIL] C[%0d][%0d] expected=%h actual=%h",
                        r,
                        c,
                        int_to_fp32(expected[r][c]),
                        c_output[r][c]
                    );

                    $fatal;

                end

            end

        end


        $display("----------------------------------------------");
        $display("[PASS] 4x4 BF16 systolic multiplication");
        $display("----------------------------------------------");


        for (r = 0; r < N; r = r + 1) begin

            $write("C[%0d] =", r);

            for (c = 0; c < N; c = c + 1) begin
                $write(" %0d", expected[r][c]);
            end

            $display("");

        end


        $display("==============================================");
        $display("ALL BF16 4x4 TESTS PASSED");
        $display("==============================================");


        $finish;

    end

endmodule
