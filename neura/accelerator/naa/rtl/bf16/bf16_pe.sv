`timescale 1ns/1ps

module bf16_pe #(
    parameter int ACC_WIDTH = 32
)(
    input  logic                 clk,
    input  logic                 rst_n,
    input  logic                 enable,

    input  logic [15:0]          a_in,
    input  logic [15:0]          b_in,
    input  logic                 a_valid_in,
    input  logic                 b_valid_in,

    output logic [15:0]          a_out,
    output logic [15:0]          b_out,
    output logic                 a_valid_out,
    output logic                 b_valid_out,

    output logic [31:0]          acc_out,
    output logic                 acc_valid
);

    /*
     * NAA BF16 PE
     *
     * BF16:
     *   bit 15    = sign
     *   bits 14:7 = exponent
     *   bits 6:0  = fraction
     *
     * Functional RTL reference:
     *
     *   BF16 x BF16 -> FP32
     *   FP32 + FP32 -> FP32
     *
     * v0.1 supports normal finite BF16 operands.
     * Zero is also handled.
     */

    function automatic [31:0] bf16_mul_fp32(
        input logic [15:0] a,
        input logic [15:0] b
    );

        logic sign_a;
        logic sign_b;
        logic sign_p;

        logic [7:0] exp_a;
        logic [7:0] exp_b;
        integer exp_p;

        logic [7:0] mant_a;
        logic [7:0] mant_b;

        logic [15:0] mant_product;

        logic [23:0] mant_fp32;

        begin
            sign_a = a[15];
            sign_b = b[15];
            sign_p = sign_a ^ sign_b;

            exp_a = a[14:7];
            exp_b = b[14:7];

            mant_a = {1'b1, a[6:0]};
            mant_b = {1'b1, b[6:0]};

            /*
             * Zero handling.
             */
            if ((exp_a == 8'd0 && a[6:0] == 7'd0) ||
                (exp_b == 8'd0 && b[6:0] == 7'd0)) begin

                bf16_mul_fp32 = 32'b0;
            end
            else begin

                mant_product = mant_a * mant_b;

                /*
                 * BF16 significand:
                 *
                 *   1.xxxxxxx
                 *
                 * Product can be:
                 *
                 *   1.xxxxxxxxxxxxxx
                 * or
                 *   10.xxxxxxxxxxxxx
                 *
                 * Normalize to FP32.
                 */
                if (mant_product[15]) begin
                    exp_p = exp_a + exp_b - 127 + 1;

                    /*
                     * Move bit 15 to FP32 hidden bit position 23.
                     */
                    mant_fp32 = mant_product << 8;
                end
                else begin
                    exp_p = exp_a + exp_b - 127;

                    /*
                     * Move bit 14 to FP32 hidden bit position 23.
                     */
                    mant_fp32 = mant_product << 9;
                end

                /*
                 * Overflow / underflow protection.
                 */
                if (exp_p >= 255) begin
                    bf16_mul_fp32 = {
                        sign_p,
                        8'hFF,
                        23'b0
                    };
                end
                else if (exp_p <= 0) begin
                    bf16_mul_fp32 = 32'b0;
                end
                else begin
                    bf16_mul_fp32 = {
                        sign_p,
                        exp_p[7:0],
                        mant_fp32[22:0]
                    };
                end
            end
        end

    endfunction


    /*
     * FP32 addition.
     *
     * v0.1 implementation is intended for the normal finite
     * values generated by the BF16 multiplier.
     *
     * Signed addition is supported.
     */
    function automatic [31:0] fp32_add(
        input logic [31:0] x,
        input logic [31:0] y
    );

        logic sx;
        logic sy;
        logic sr;

        logic [7:0] ex;
        logic [7:0] ey;
        integer er;

        logic [23:0] mx;
        logic [23:0] my;

        logic [24:0] sum;

        logic [23:0] mant_big;
        logic [23:0] mant_small;

        logic sign_big;
        logic sign_small;

        integer shift;
        integer i;

        begin

            sx = x[31];
            sy = y[31];

            ex = x[30:23];
            ey = y[30:23];

            /*
             * Zero fast paths.
             */
            if (x[30:0] == 0) begin
                fp32_add = y;
            end
            else if (y[30:0] == 0) begin
                fp32_add = x;
            end
            else begin

                /*
                 * Restore hidden bit.
                 */
                mx = {1'b1, x[22:0]};
                my = {1'b1, y[22:0]};

                /*
                 * Align exponents.
                 */
                if (ex >= ey) begin

                    shift = ex - ey;

                    if (shift > 24)
                        mant_small = 24'b0;
                    else
                        mant_small = my >> shift;

                    mant_big  = mx;
                    sign_big  = sx;
                    sign_small = sy;
                    er = ex;

                end
                else begin

                    shift = ey - ex;

                    if (shift > 24)
                        mant_small = 24'b0;
                    else
                        mant_small = mx >> shift;

                    mant_big  = my;
                    sign_big  = sy;
                    sign_small = sx;
                    er = ey;

                end

                /*
                 * Same sign -> addition.
                 */
                if (sign_big == sign_small) begin

                    sum = {1'b0, mant_big} +
                          {1'b0, mant_small};

                    sr = sign_big;

                    /*
                     * Carry out.
                     */
                    if (sum[24]) begin
                        sum = sum >> 1;
                        er = er + 1;
                    end

                    if (er >= 255) begin
                        fp32_add = {
                            sr,
                            8'hFF,
                            23'b0
                        };
                    end
                    else begin
                        fp32_add = {
                            sr,
                            er[7:0],
                            sum[22:0]
                        };
                    end

                end
                else begin

                    /*
                     * Different signs -> subtraction.
                     */
                    if (mant_big >= mant_small) begin
                        sum = {
                            1'b0,
                            mant_big
                        } - {
                            1'b0,
                            mant_small
                        };

                        sr = sign_big;
                    end
                    else begin
                        sum = {
                            1'b0,
                            mant_small
                        } - {
                            1'b0,
                            mant_big
                        };

                        sr = sign_small;
                    end

                    /*
                     * Normalize left.
                     */
                    for (i = 0; i < 24; i = i + 1) begin
                        if (sum[23] == 1'b0 &&
                            sum != 0) begin
                            sum = sum << 1;
                            er = er - 1;
                        end
                    end

                    if (sum == 0) begin
                        fp32_add = 32'b0;
                    end
                    else if (er <= 0) begin
                        fp32_add = 32'b0;
                    end
                    else begin
                        fp32_add = {
                            sr,
                            er[7:0],
                            sum[22:0]
                        };
                    end
                end
            end
        end

    endfunction


    logic [31:0] product_fp32;
    logic [31:0] accumulated_fp32;


    always_comb begin
        product_fp32 = bf16_mul_fp32(a_in, b_in);

        if (!acc_valid)
            accumulated_fp32 = product_fp32;
        else
            accumulated_fp32 = fp32_add(
                acc_out,
                product_fp32
            );
    end


    always_ff @(posedge clk) begin

        if (!rst_n) begin

            a_out       <= 16'b0;
            b_out       <= 16'b0;

            a_valid_out <= 1'b0;
            b_valid_out <= 1'b0;

            acc_out     <= 32'b0;
            acc_valid   <= 1'b0;

        end
        else if (enable) begin

            /*
             * Systolic forwarding.
             */
            a_out <= a_in;
            b_out <= b_in;

            a_valid_out <= a_valid_in;
            b_valid_out <= b_valid_in;

            /*
             * MAC operation.
             */
            if (a_valid_in && b_valid_in) begin

                acc_out   <= accumulated_fp32;
                acc_valid <= 1'b1;

            end

        end
        else begin

            a_valid_out <= 1'b0;
            b_valid_out <= 1'b0;

        end

    end

endmodule
